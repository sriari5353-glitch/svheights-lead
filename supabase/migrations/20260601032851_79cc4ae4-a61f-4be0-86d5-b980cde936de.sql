-- Fix: profiles table exposed all users' emails/info to any authenticated user.
-- Switching users is admin-only now, so restrict profile visibility to owner + admins.
DROP POLICY IF EXISTS "All authenticated users can view profiles" ON public.profiles;

-- Harden user_roles: add explicit admin-only management policies so privilege escalation is impossible.
CREATE POLICY "Admins can view all roles"
ON public.user_roles
FOR SELECT
TO authenticated
USING (public.has_role(auth.uid(), 'admin'));

CREATE POLICY "Admins can insert roles"
ON public.user_roles
FOR INSERT
TO authenticated
WITH CHECK (public.has_role(auth.uid(), 'admin'));

CREATE POLICY "Admins can update roles"
ON public.user_roles
FOR UPDATE
TO authenticated
USING (public.has_role(auth.uid(), 'admin'))
WITH CHECK (public.has_role(auth.uid(), 'admin'));

CREATE POLICY "Admins can delete roles"
ON public.user_roles
FOR DELETE
TO authenticated
USING (public.has_role(auth.uid(), 'admin'));